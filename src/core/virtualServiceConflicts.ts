function strings(value: unknown, field: string): string[] {
  if (value === undefined || value === null) return [];
  if (
    !Array.isArray(value) ||
    value.length > 100 ||
    value.some(item => typeof item !== 'string' || item.length > 1024)
  )
    throw new Error(`VirtualService conflicts require at most 100 bounded strings in ${field}`);
  return value;
}

function fields(spec: Record<string, unknown>) {
  return {
    hosts: strings(spec.hosts, 'hosts'),
    gateways: strings(spec.gateways, 'gateways'),
    exportTo: configurationExports(spec),
  };
}

export function virtualServiceNeedsConflicts(
  kind: string,
  group: string,
  spec: Record<string, unknown>,
  domain: string | null
): boolean {
  if (kind !== 'VirtualService' || group !== 'networking.istio.io' || !isDnsSubdomain(domain))
    return false;
  return Array.isArray(spec.hosts) && spec.hosts.length > 0 && spec.hosts.length <= 100;
}

export function virtualServiceHostConflicts(
  records: readonly Pick<ValidationRecord, 'name' | 'namespace' | 'spec'>[],
  namespaces: readonly string[],
  domain: string,
  selectedIndex: number
): { conflict: boolean; references: number[] } {
  if (
    records.length > 1000 ||
    namespaces.length > 1000 ||
    !isDnsSubdomain(domain) ||
    !Number.isInteger(selectedIndex) ||
    selectedIndex < 0 ||
    selectedIndex >= records.length
  )
    throw new Error('VirtualService conflicts require bounded records and a selected identity');
  const groups = new Map<string, Map<string, number[]>>();
  let contributions = 0;
  records.forEach((record, index) => {
    const parsed = fields(record.spec);
    const gateways = parsed.gateways.length ? parsed.gateways : ['no-gateway'];
    contributions += parsed.hosts.length * gateways.length;
    if (contributions > 20000)
      throw new Error('VirtualService conflicts exceed 20000 gateway-host contributions');
    for (const raw of parsed.hosts) {
      const host = getHost(raw, record.namespace, namespaces, domain);
      for (const gateway of gateways) {
        const key = JSON.stringify([gateway, host.identityDomain, host.namespace]);
        let services = groups.get(key);
        if (!services) {
          services = new Map();
          groups.set(key, services);
        }
        const counter = services.get(host.service) ?? [];
        counter.push(index);
        services.set(host.service, counter);
      }
    }
  });
  let conflict = false;
  const references = new Set<number>();
  const add = (indices: readonly number[]) => {
    conflict = true;
    for (const index of indices) if (index !== selectedIndex) references.add(index);
  };
  for (const services of groups.values()) {
    const wildcard = services.get('*') ?? [];
    for (const counter of services.values()) {
      if (!counter.includes(selectedIndex)) continue;
      if (counter.length > 1) add(counter);
      if (wildcard.length && services.size > 1) {
        if (wildcard.includes(selectedIndex)) {
          for (const peers of services.values()) add(peers);
        } else add(wildcard);
      }
    }
  }
  return { conflict, references: [...references].sort((a, b) => a - b) };
}

export function virtualServiceConflictChecks(
  kind: string,
  group: string,
  namespace: string,
  spec: Record<string, unknown>,
  context?: ReferenceValidationContext,
  owner?: ValidationOwner
): { findings: Finding[]; skipped: string[] } {
  if (kind !== 'VirtualService' || group !== 'networking.istio.io')
    return { findings: [], skipped: [] };
  try {
    const target = fields(spec);
    if (!target.hosts.length || owner?.name.includes('autogenerated-k8s'))
      return { findings: [], skipped: [] };
    const domain = context?.identityDomain;
    if (!context || !domain || !isDnsSubdomain(domain))
      throw new Error(
        'VirtualService conflict checks require an explicit Service DNS identity domain'
      );
    if (
      !isDnsLabel(namespace) ||
      !owner ||
      !isDnsSubdomain(owner.name) ||
      !owner.uid ||
      owner.uid.trim() !== owner.uid
    )
      throw new Error(
        'VirtualService conflict checks require the captured namespace, name and UID'
      );
    if (
      !context.namespaces.complete ||
      !context.virtualServices?.complete ||
      !context.sidecars.complete ||
      [context.namespaces.items, context.virtualServices.items, context.sidecars.items].some(
        items => items.length > 1000
      )
    )
      throw new Error(
        'VirtualService conflict checks require complete bounded Namespace, VirtualService and Sidecar lists'
      );
    const records = namespacedValidationRecords(context.virtualServices.items);
    const selected = records.find(
      record => record.name === owner.name && record.namespace === namespace
    );
    if (
      !selected ||
      selected.uid !== owner.uid ||
      JSON.stringify(fields(selected.spec)) !== JSON.stringify(target)
    )
      throw new Error(
        'VirtualService identity or relevant specification changed; reload before checking conflicts'
      );
    const namespaces = context.namespaces.items.map(item => item.name);
    if (!namespaces.includes(namespace))
      throw new Error('Selected namespace is missing from VirtualService context');
    const scope = configurationImportScope(namespace, context);
    const visible = records.filter(record => {
      if (record.name.includes('autogenerated-k8s')) return false;
      if (!configurationExportIncluded('VirtualService', record, namespace, context)) return false;
      // The pinned caller imports whole objects, not individual host contributions.
      return (
        !scope.limited ||
        fields(record.spec).hosts.some(host => importsHost(scope, host, record.namespace))
      );
    });
    const index = visible.indexOf(selected);
    if (index < 0)
      return {
        findings: [],
        skipped: [
          'Selected VirtualService is not exported and imported into this namespace validation scope',
        ],
      };
    const result = virtualServiceHostConflicts(visible, namespaces, domain, index);
    return {
      skipped: [],
      findings: result.conflict
        ? [
            {
              code: 'KIA1106',
              severity: 'warning',
              path: 'spec/hosts',
              message: 'More than one Virtual Service for same host',
              references: result.references
                .map((index): NonNullable<Finding['references']>[number] => ({
                  kind: 'VirtualService',
                  group: 'networking.istio.io',
                  namespace: visible[index].namespace,
                  name: visible[index].name,
                  uid: visible[index].uid,
                }))
                .sort((a, b) =>
                  JSON.stringify([a.namespace, a.name]).localeCompare(
                    JSON.stringify([b.namespace, b.name])
                  )
                ),
            },
          ]
        : [],
    };
  } catch (error) {
    return {
      findings: [],
      skipped: [
        error instanceof Error ? error.message : 'Unable to evaluate VirtualService conflicts',
      ],
    };
  }
}
