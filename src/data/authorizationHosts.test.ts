import { ApiProxy } from '@kinvolk/headlamp-plugin/lib';
import { referenceValidation } from '../core/referenceValidation';
import { clusterScope } from '../core/scope';
import { loadValidationSnapshot } from './validation';

vi.mock('@kinvolk/headlamp-plugin/lib', () => ({
  ApiProxy: { request: vi.fn() },
  K8s: { cluster: { KubeObject: class {} } },
}));
const group = 'networking.istio.io';
const collection = (kind: string, apiVersion: string, items: unknown[]) => ({
  kind: `${kind}List`,
  apiVersion,
  metadata: { resourceVersion: '1' },
  items,
});
beforeEach(() => {
  vi.mocked(ApiProxy.request).mockReset();
});
it.each([
  'visible-vs',
  'private-vs',
  'missing',
  'service',
  'autogenerated',
  'denied-vs',
  'denied-namespaces',
  'denied-mesh',
  'external',
  'wildcard',
  'no-domain',
  'malformed-hosts',
])('captures and limits sources for %s while retaining local method checks', async mode => {
  const requests: string[] = [];
  vi.mocked(ApiProxy.request).mockImplementation(async path => {
    const url = new URL(String(path), 'http://example.test');
    requests.push(url.pathname);
    if (url.pathname === '/api/v1/namespaces') {
      if (mode === 'denied-namespaces') throw { status: 403, message: 'Namespaces denied' };
      return collection(
        'Namespace',
        'v1',
        ['bookinfo', 'other', 'root'].map(name => ({
          metadata: { name, uid: name, labels: { 'istio.io/rev': 'blue' } },
        }))
      );
    }
    if (url.pathname === `/apis/${group}`)
      return { name: group, versions: [{ groupVersion: `${group}/v1` }] };
    if (url.pathname === `/apis/${group}/v1`)
      return {
        groupVersion: `${group}/v1`,
        resources: [
          { name: 'serviceentries', kind: 'ServiceEntry', namespaced: true },
          { name: 'virtualservices', kind: 'VirtualService', namespaced: true },
        ],
      };
    if (url.pathname === '/api/v1/services')
      return collection(
        'Service',
        'v1',
        mode === 'service'
          ? [
              {
                metadata: {
                  name: 'reviews',
                  namespace: 'bookinfo',
                  uid: 'service',
                  annotations: { 'networking.istio.io/exportTo': '*' },
                },
                spec: {},
              },
            ]
          : []
      );
    if (url.pathname.endsWith('/serviceentries'))
      return collection('ServiceEntry', `${group}/v1`, []);
    if (url.pathname.endsWith('/virtualservices')) {
      if (mode === 'denied-vs') throw { status: 403, message: 'VirtualServices denied' };
      return collection(
        'VirtualService',
        `${group}/v1`,
        ['visible-vs', 'private-vs', 'autogenerated', 'denied-mesh'].includes(mode)
          ? [
              {
                metadata: {
                  name: mode === 'autogenerated' ? 'route-autogenerated-k8s-test' : 'route',
                  namespace: 'other',
                  uid: 'route',
                },
                spec: { hosts: ['reviews.bookinfo'] },
              },
            ]
          : []
      );
    }
    if (url.pathname === '/apis/apps/v1/deployments')
      return collection('Deployment', 'apps/v1', [
        {
          metadata: {
            name: 'istiod-blue',
            namespace: 'root',
            uid: 'controller',
            labels: { app: 'istiod', 'istio.io/rev': 'blue' },
          },
          spec: { template: { spec: { containers: [{ name: 'discovery' }] } } },
        },
      ]);
    if (url.pathname.endsWith('/mutatingwebhookconfigurations'))
      return collection('MutatingWebhookConfiguration', 'admissionregistration.k8s.io/v1', []);
    if (url.pathname.includes('/configmaps/')) {
      if (mode === 'denied-mesh') throw { status: 403, message: 'Mesh denied' };
      const name = url.pathname.split('/').pop();
      return {
        kind: 'ConfigMap',
        apiVersion: 'v1',
        metadata: { name, namespace: 'root' },
        data: name?.includes('sidecar-injector')
          ? { values: '{}' }
          : {
              mesh: `rootNamespace: root\ndefaultVirtualServiceExportTo: [${
                mode === 'private-vs' ? '"."' : '"bookinfo"'
              }]\noutboundTrafficPolicy: {mode: ALLOW_ANY}`,
            },
      };
    }
    throw new Error(`Unexpected authorization context request ${path}`);
  });
  const input = {
    rules: [
      {
        to: [
          {
            operation: {
              hosts:
                mode === 'malformed-hosts'
                  ? [false]
                  : [
                      mode === 'external'
                        ? 'api.info'
                        : mode === 'wildcard'
                        ? '*.bookinfo'
                        : 'reviews',
                    ],
              methods: ['INVALID'],
            },
          },
        ],
      },
    ],
  };
  const captured = structuredClone(input);
  const pending = loadValidationSnapshot(
    clusterScope('alpha'),
    'AuthorizationPolicy',
    'security.istio.io',
    input,
    mode === 'no-domain' ? null : 'svc.cluster.local',
    new AbortController().signal,
    'bookinfo'
  );
  input.rules = [];
  const snapshot = await pending;
  const result = referenceValidation(
    'AuthorizationPolicy',
    'security.istio.io',
    'bookinfo',
    captured,
    snapshot.context
  );
  expect(result.findings.filter(finding => finding.code === 'KIA0102')).toHaveLength(1);
  expect(result.findings.filter(finding => finding.code === 'KIA0104')).toHaveLength(
    ['private-vs', 'missing', 'autogenerated'].includes(mode) ? 1 : 0
  );
  expect(result.skipped.length > 0).toBe(
    ['denied-vs', 'denied-namespaces', 'denied-mesh', 'no-domain', 'malformed-hosts'].includes(mode)
  );
  const noContext = ['wildcard', 'malformed-hosts'].includes(mode);
  const onlyNamespaces = ['external', 'denied-namespaces', 'no-domain'].includes(mode);
  expect(snapshot.sources.map(source => source.key)).toEqual(
    noContext
      ? []
      : onlyNamespaces
      ? ['namespaces']
      : ['namespaces', 'services', 'serviceEntries', 'virtualServices']
  );
  if (noContext) expect(requests).toEqual([]);
  if (onlyNamespaces) expect(requests).toEqual(['/api/v1/namespaces']);
  if (mode === 'denied-vs') expect(requests).not.toContain('/apis/apps/v1/deployments');
  if (mode === 'visible-vs')
    expect(snapshot.context.namespaceMesh?.get('other')?.status).toBe('ready');
  for (const [, options] of vi.mocked(ApiProxy.request).mock.calls)
    expect(options).toMatchObject({ cluster: 'alpha', signal: expect.any(AbortSignal) });
});
